import { writeFile } from "node:fs/promises";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { Globe } from "lucide-react";
import { format, resolveConfig } from "prettier";

// Satori cannot run Lucide's React hooks, and Next route handlers cannot import
// react-dom/server. Preserve the installed official glyph as a generated asset.
const svg = renderToStaticMarkup(
    createElement(Globe, { size: 24, color: "#a0a0aa", strokeWidth: 2 })
);
const destination = new URL(
    "../features/profile/profileCardGlobe.ts",
    import.meta.url
);
const source =
    `// Generated by scripts/generate-profile-card-icon.mjs from lucide-react Globe.\n` +
    `// Lucide v1.24.0, ISC license; geometry is unmodified.\n` +
    `export const profileCardGlobe = ${JSON.stringify(`data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`)};\n`;
await writeFile(
    destination,
    await format(source, {
        ...(await resolveConfig(destination)),
        parser: "typescript",
    })
);
